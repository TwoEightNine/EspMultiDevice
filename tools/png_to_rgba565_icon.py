#!/usr/bin/env python3
"""Convert an RGBA PNG into compile-time RGB565 and alpha arrays.

The emitted arrays live in program flash (`PROGMEM`) and are intended for a
renderer that alpha-blends each RGB565 pixel with the immediate background
colour. This preserves the source icon's colours and anti-aliased edges
without requiring an SD card at runtime.

Requires Pillow: python3 -m pip install Pillow

Examples:
  tools/png_to_rgba565_icon.py assets/files.png --name ic_files > src/ui/icons/files.h
  tools/png_to_rgba565_icon.py assets/files.png --name ic_files --output src/ui/icons/files.h
"""

import argparse
from pathlib import Path
import re
import sys
from typing import Any, Iterable


def identifier(value: str) -> str:
    """Return a safe C++ identifier, using an icon-oriented prefix if needed."""
    name = re.sub(r"[^A-Za-z0-9_]", "_", value)
    if not name or name[0].isdigit():
        name = f"ic_{name}"
    return name


def rgb888_to_rgb565(red: int, green: int, blue: int) -> int:
    """Pack an 8-bit RGB colour into the display's RGB565 representation."""
    return ((red & 0xF8) << 8) | ((green & 0xFC) << 3) | (blue >> 3)


def convert(image: Any) -> tuple[int, int, list[int], list[int]]:
    """Return width, height, straight RGB565 pixels, and 8-bit alpha values."""
    width, height = image.size
    if not width or not height:
        raise ValueError("PNG must have a non-zero width and height.")
    if width > 0xFFFF or height > 0xFFFF:
        raise ValueError("PNG dimensions must fit in uint16_t.")

    rgba = image.convert("RGBA")
    colors: list[int] = []
    alpha: list[int] = []
    pixels = (rgba.get_flattened_data()
              if hasattr(rgba, "get_flattened_data") else rgba.getdata())
    for red, green, blue, opacity in pixels:
        colors.append(rgb888_to_rgb565(red, green, blue))
        alpha.append(opacity)
    return width, height, colors, alpha


def chunks(values: list[int], size: int) -> Iterable[list[int]]:
    for offset in range(0, len(values), size):
        yield values[offset:offset + size]


def format_array(c_type: str, name: str, values: list[int], digits: int, row_size: int) -> str:
    rows = [", ".join(f"0x{value:0{digits}X}" for value in row)
            for row in chunks(values, row_size)]
    body = ",\n    ".join(rows)
    return f"const {c_type} {name}[{len(values)}] PROGMEM = {{\n    {body}\n}};"


def format_header(name: str,
                  width: int,
                  height: int,
                  colors: list[int],
                  alpha: list[int]) -> str:
    return "\n".join((
        "#pragma once",
        "",
        "#include <Arduino.h>",
        "",
        "// Generated by tools/png_to_rgba565_icon.py. Do not hand-edit.",
        "// Colors use straight RGB565; alpha is 0 (transparent) through 255 (opaque).",
        f"constexpr uint16_t {name}_width = {width};",
        f"constexpr uint16_t {name}_height = {height};",
        "",
        format_array("uint16_t", f"{name}_colors", colors, 4, 8),
        "",
        format_array("uint8_t", f"{name}_alpha", alpha, 2, 16),
        "",
    ))


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("input", help="source PNG with optional transparency")
    parser.add_argument("--name", default="ic_icon",
                        help="C++ identifier prefix (default: ic_icon)")
    parser.add_argument("--output", type=Path,
                        help="generated header path; omit to write to stdout")
    args = parser.parse_args()

    try:
        from PIL import Image
    except ImportError:
        sys.exit("Pillow is required. Install it with: python3 -m pip install Pillow")

    try:
        with Image.open(args.input) as image:
            width, height, colors, alpha = convert(image)
    except (OSError, ValueError) as error:
        parser.error(str(error))

    header = format_header(identifier(args.name), width, height, colors, alpha)
    if args.output:
        args.output.write_text(header, encoding="utf-8")
    else:
        print(header, end="")


if __name__ == "__main__":
    main()
