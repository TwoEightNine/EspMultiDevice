#!/usr/bin/env python3
"""Generate the assistant-only Noto Sans CJK SC smooth-font header.

Download NotoSansCJKsc-Regular.otf from the official Noto CJK project, then
run:

  python3 tools/generate_assistant_noto_sans_sc_font.py \
      /path/to/NotoSansCJKsc-Regular.otf > src/ui/fonts/AssistantNotoSansSC18.h

The generated 18 px face contains printable Latin, Latin-1, Cyrillic, and all
characters encodable by GB2312. It is deliberately limited to assistant
captions, so the rest of the UI retains its smaller FreeSans faces.
"""

import struct
import sys

from PIL import Image, ImageDraw, ImageFont


POINT_SIZE = 18


def be32(value):
    return struct.pack(">i", value)


def gb2312_codepoints():
    result = set()
    for lead in range(0xA1, 0xF8):
        for trail in range(0xA1, 0xFF):
            try:
                text = bytes((lead, trail)).decode("gb2312")
            except UnicodeDecodeError:
                continue
            result.update(ord(character) for character in text)
    return result


def glyph_codes():
    latin = set(range(0x20, 0x7F)) | set(range(0xA0, 0x100))
    cyrillic = set(range(0x400, 0x500))
    extras = {
        0x0192, 0x02C6, 0x02DC, 0x0152, 0x0153, 0x0160, 0x0161,
        0x0178, 0x017D, 0x017E, 0x2013, 0x2014, 0x2018, 0x2019,
        0x201A, 0x201C, 0x201D, 0x201E, 0x2020, 0x2021, 0x2022,
        0x2026, 0x2030, 0x2039, 0x203A, 0x20AC, 0x2116, 0x2122,
        0xFFFD,
    }
    return sorted(latin | cyrillic | extras | gb2312_codepoints())


def main():
    if len(sys.argv) != 2:
        raise SystemExit("usage: generate_assistant_noto_sans_sc_font.py FONT.otf")

    font = ImageFont.truetype(sys.argv[1], POINT_SIZE)
    ascent, descent = font.getmetrics()
    metrics = []
    bitmaps = []
    for codepoint in glyph_codes():
        character = chr(codepoint)
        bbox = font.getbbox(character, anchor="ls")
        advance = round(font.getlength(character))
        if bbox is None:
            left = top = width = height = 0
            pixels = b""
        else:
            left, top, right, bottom = bbox
            width, height = max(0, right - left), max(0, bottom - top)
            glyph = Image.new("L", (max(1, width), max(1, height)), 0)
            ImageDraw.Draw(glyph).text((-left, -top), character, font=font,
                                        fill=255, anchor="ls")
            pixels = glyph.crop((0, 0, width, height)).tobytes() if width and height else b""
        metrics.append((codepoint, height, width, advance, -top, left, 0))
        bitmaps.append(pixels)

    data = bytearray(be32(len(metrics)) + be32(11) + be32(POINT_SIZE) +
                     be32(0) + be32(ascent) + be32(descent))
    for metric in metrics:
        for value in metric:
            data += be32(value)
    for bitmap in bitmaps:
        data += bitmap
    name = b"NotoSansCJKSC18"
    data += bytes((len(name),)) + name + bytes((len(name),)) + name + b"\x01"

    print("#pragma once\n")
    print("// Assistant-only Noto Sans CJK SC 18 px smooth font.")
    print("// Generated by tools/generate_assistant_noto_sans_sc_font.py from")
    print("// NotoSansCJKsc-Regular.otf (SIL Open Font License 1.1; see")
    print("// src/ui/fonts/LICENSE.NotoSansCJKSC). Glyph coverage: GB2312, Latin,")
    print("// Latin-1, Cyrillic, and common punctuation.")
    print("const uint8_t AssistantNotoSansSC18[] PROGMEM = {")
    for offset in range(0, len(data), 16):
        print(", ".join(f"0x{value:02X}" for value in data[offset:offset + 16]) + ",")
    print("};")


if __name__ == "__main__":
    main()
